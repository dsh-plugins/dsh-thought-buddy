#!/usr/bin/env node
/**
 * gen-data-lib.mjs — gen-data.mjs 的纯函数库（可被迁移脚本 / 测试复用）：
 *
 *   parseExpressions / parseShapes / parseStates
 *       从 GrokBot Dart 数据源解析（ref/GrokBot/lib/src/data/*.dart）
 *   parseDataTs(source)
 *       从现有 src/client/data.ts（或旧 data.js）回读三个 const，用于
 *       ref/ 缺失时的幂等再生成
 *   renderDataTs({ expressions, shapes, states })
 *       渲染 src/client/data.ts（纯脚本、无 import/export，保持 __ModuleLoader__
 *       拼接契约；仅含全局类型声明与三个带注解的 const）
 */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const outFile = join(root, 'src', 'client', 'data.ts')
export const refDataDir = join(root, 'ref', 'GrokBot', 'lib', 'src', 'data')

/** 全部 Offset(x, y) 按顺序取出，每 96 个点（2 眼 × 48）为一个表情。 */
export function parseExpressions(source) {
  const points = []
  const re = /Offset\(\s*([-\d.]+)\s*,\s*([-\d.]+)\s*\)/g
  let m
  while ((m = re.exec(source)) !== null) {
    points.push([Number(m[1]), Number(m[2])])
  }
  const PER_EXPRESSION = 96 // 2 eyes × 48 points
  if (points.length % PER_EXPRESSION !== 0) {
    throw new Error(`expression points not divisible: ${points.length}`)
  }
  const expressions = []
  for (let i = 0; i < points.length; i += PER_EXPRESSION) {
    const chunk = points.slice(i, i + PER_EXPRESSION)
    const eyeL = chunk.slice(0, 48)
    const eyeR = chunk.slice(48, 96)
    expressions.push([eyeL, eyeR])
  }
  return expressions
}

/** 每个 GrokBotShape.X: GrokBotShapeData(...) 条目解析出 9 个字段。 */
export function parseShapes(source) {
  const shapes = {}
  const entryRe = /GrokBotShape\.(\w+):\s*GrokBotShapeData\(([\s\S]*?)\),\s*$/gm
  const fieldRe = /([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*(true|false)\s*,\s*'([^']*)'\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)/g
  let m
  while ((m = entryRe.exec(source)) !== null) {
    const name = m[1]
    const fields = m[2]
    fieldRe.lastIndex = 0
    const f = fieldRe.exec(fields)
    if (!f) throw new Error(`shape fields not parsed: ${name}`)
    shapes[name] = {
      faceX: Number(f[1]),
      faceY: Number(f[2]),
      faceScaleX: Number(f[3]),
      faceScaleY: Number(f[4]),
      eyeScale: Number(f[5]),
      squashOnTurn: f[6] === 'true',
      radius: f[7],
      aspectX: Number(f[8]),
      aspectY: Number(f[9]),
    }
  }
  return shapes
}

/** 每个 GrokBotState.X: GrokBotStateData(...) 条目解析出表情池与两个节奏。 */
export function parseStates(source) {
  const states = {}
  const entryRe =
    /GrokBotState\.(\w+):\s*GrokBotStateData\(\s*_expressions\(\[([\d,\s]+)\]\),\s*_cadence\((\d+),\s*(\d+)\),\s*(?:_cadence\((\d+),\s*(\d+)\))?/g
  let m
  while ((m = entryRe.exec(source)) !== null) {
    const name = m[1]
    const indexes = m[2].split(',').map((s) => Number(s.trim()))
    states[name] = {
      expressions: indexes,
      expressionMin: Number(m[3]),
      expressionMax: Number(m[4]),
      blinkMin: m[5] !== undefined ? Number(m[5]) : null,
      blinkMax: m[6] !== undefined ? Number(m[6]) : null,
    }
  }
  return states
}

/** 从 data.ts / 旧 data.js 回读三个 const（RHS 为纯 JSON，可安全 JSON.parse）。 */
export function parseDataTs(source) {
  const grab = (name) => {
    const re = new RegExp(`^const ${name}(?:\\s*:\\s*[^=]+)?\\s*=\\s*(.*);$`, 'm')
    const m = re.exec(source)
    if (m === null) throw new Error(`cannot find const ${name} in data source`)
    return JSON.parse(m[1])
  }
  return {
    expressions: grab('TB_EXPRESSIONS'),
    shapes: grab('TB_SHAPES'),
    states: grab('TB_STATES'),
  }
}

const HEADER = `/* Generated by scripts/gen-data.mjs from nasawz/GrokBot (BSD-3-Clause, (c) 2026 nasawz,
   https://github.com/nasawz/GrokBot). Ported geometry: 25 expressions × 2 eyes × 48
   points, 18 body shapes (CSS border-radius syntax), 39 states with expression/blink
   cadences. Do not edit by hand — re-run the generator after upstream changes. */`

const TYPES = `/** 单个眼环点（SVG 坐标）。 */
type TbPoint = [number, number];

/** 单只眼睛的 48 点眼环。 */
type TbEyeRing = TbPoint[];

/** 一个表情：左眼 + 右眼眼环。 */
type TbExpression = [TbEyeRing, TbEyeRing];

/** 身体形态参数（radius 为 CSS border-radius 语法）。 */
interface TbShape {
  faceX: number;
  faceY: number;
  faceScaleX: number;
  faceScaleY: number;
  eyeScale: number;
  squashOnTurn: boolean;
  radius: string;
  aspectX: number;
  aspectY: number;
}

/** 状态：表情池 + 表情/眨眼节奏（blinkMin 为 null 表示不眨眼）。 */
interface TbState {
  expressions: number[];
  expressionMin: number;
  expressionMax: number;
  blinkMin: number | null;
  blinkMax: number | null;
}`

export function renderDataTs({ expressions, shapes, states }) {
  return [
    HEADER,
    '',
    TYPES,
    '',
    `const TB_EXPRESSIONS: TbExpression[] = ${JSON.stringify(expressions)};`,
    `const TB_SHAPES: Record<string, TbShape> = ${JSON.stringify(shapes)};`,
    `const TB_STATES: Record<string, TbState> = ${JSON.stringify(states)};`,
    '',
  ].join('\n')
}

/** ref/ 数据源是否齐全（CI 上 ref/ 被 git 忽略，通常缺失）。 */
export function refDataPresent() {
  return ['expression_data.dart', 'shape_data.dart', 'state_data.dart'].every(
    (f) => {
      try {
        readFileSync(join(refDataDir, f), 'utf8')
        return true
      } catch {
        return false
      }
    },
  )
}
